import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.ObjectInputStream;
import java.io.ObjectOutputStream;
import java.io.Serializable;
import java.lang.reflect.Constructor;
import java.lang.reflect.Field;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.List;
import java.util.TreeSet;

/**
 * Core reflection under each accessor backend. JDK 21 defaults to method-handle accessors;
 * -Djdk.reflect.useDirectMethodHandle=false restores the native accessors that inflate into
 * generated bytecode accessors (-Dsun.reflect.inflationThreshold=N, -Dsun.reflect.noInflation=true),
 * and -Djdk.reflect.useNativeAccessorOnly=true keeps the native path. The probe prints which
 * accessor kinds it observed on the stack (fixed by the flags) and checks invocation, boxing and
 * widening, argument errors, exceptions, constructors, field access and serialization
 * constructors across many distinct members, so each gets its own accessor.
 */
public final class LegacyReflect {
    static final TreeSet<String> kinds = new TreeSet<>();

    static String kind(String cls) {
        if (cls.startsWith("jdk.internal.reflect.GeneratedMethodAccessor")) return "generatedMethod";
        if (cls.startsWith("jdk.internal.reflect.GeneratedConstructorAccessor")) return "generatedConstructor";
        if (cls.startsWith("jdk.internal.reflect.GeneratedSerializationConstructorAccessor")) return "generatedSerialization";
        if (cls.equals("jdk.internal.reflect.NativeMethodAccessorImpl")) return "nativeMethod";
        if (cls.equals("jdk.internal.reflect.NativeConstructorAccessorImpl")) return "nativeConstructor";
        if (cls.equals("jdk.internal.reflect.DirectMethodHandleAccessor")) return "directMethodHandle";
        if (cls.equals("jdk.internal.reflect.DirectConstructorHandleAccessor")) return "directConstructorHandle";
        if (cls.startsWith("jdk.internal.reflect.DirectMethodHandleAccessor$NativeAccessor")) return "directNative";
        if (cls.startsWith("jdk.internal.reflect.DirectConstructorHandleAccessor$NativeAccessor")) return "directConstructorNative";
        return null;
    }

    static final StackWalker WALKER = StackWalker.getInstance(java.util.Set.of(
        StackWalker.Option.SHOW_REFLECT_FRAMES, StackWalker.Option.SHOW_HIDDEN_FRAMES));

    static void observe(String phase) {
        WALKER.forEach(f -> {
            String k = kind(f.getClassName());
            if (k != null) kinds.add(phase + ":" + k);
        });
    }

    public static class Target {
        public int i;
        public long l;
        public double d;
        public volatile Object o;
        private short s;
        public static final int FIXED = 3;
        public final long seed;
        static boolean watch;
        static String phase = "early";

        public Target() { this(1); }
        public Target(long seed) {
            this.seed = seed;
            if (watch) observe(phase + "Ctor");
        }

        public long m0(long a) { if (watch) observe(phase); return a + seed; }
        public long m1(int a, long b) { return a * b + seed; }
        public double m2(double a, float b) { return a * b; }
        public static long s0(long a, short b, byte c, char d) { return a + b + c + d; }
        private int p0(int a) { return a ^ s; }
        public String v0(String... parts) { return String.join("+", parts); }
        public void boom(int a) { if (a % 3 == 0) throw new IllegalStateException("boom" + a); }
    }

    public static final class Ser implements Serializable {
        private static final long serialVersionUID = 1L;
        final int a;
        final String b;
        Ser(int a, String b) { this.a = a; this.b = b; }
    }

    /** Generated members: many distinct methods so each Method gets its own accessor. */
    public static class Many {
        public long a0(long x) { return x + 0; } public long a1(long x) { return x + 1; }
        public long a2(long x) { return x * 2; } public long a3(long x) { return x ^ 3; }
        public long a4(long x) { return x - 4; } public long a5(long x) { return x << 1; }
        public long a6(long x) { return x >>> 1; } public long a7(long x) { return ~x; }
        public long a8(long x) { return x * 31; } public long a9(long x) { return -x; }
        public static long b0(long x) { return x + 100; } public static long b1(long x) { return x * 3; }
        public static long b2(long x) { return x ^ 0x55; } public static long b3(long x) { return x - 7; }
    }

    static String err(Throwable t) {
        if (t instanceof InvocationTargetException ite) return "ITE<" + ite.getCause().getClass().getSimpleName();
        return t.getClass().getSimpleName();
    }

    public static void main(String[] args) throws Exception {
        Fz.init("LegacyReflect", args);
        Target t = new Target(Fz.rnd.nextInt(1000));
        Method m0 = Target.class.getMethod("m0", long.class);
        Target.watch = true;
        m0.invoke(t, 1L);
        Target.class.getConstructor(long.class).newInstance(5L);
        Target.phase = "late";
        long acc = 0;
        int n = 20_000 * Fz.scale;
        Method m1 = Target.class.getMethod("m1", int.class, long.class), m2 = Target.class.getMethod("m2", double.class, float.class);
        Method s0 = Target.class.getMethod("s0", long.class, short.class, byte.class, char.class);
        Method p0 = Target.class.getDeclaredMethod("p0", int.class);
        p0.setAccessible(true);
        Method v0 = Target.class.getMethod("v0", String[].class), boom = Target.class.getMethod("boom", int.class);
        Constructor<Target> ctor = Target.class.getConstructor(long.class);
        Target.watch = false;
        int thrown = 0;
        for (int k = 0; k < n; k++) {
            if (k == n - 1) Target.watch = true;
            acc = acc * 31 + (long) m0.invoke(t, (long) k);
            // Widening: Integer to long, Short to int, Float to double.
            acc += (long) m1.invoke(t, (short) k, k);
            acc += Double.doubleToLongBits((double) m2.invoke(t, (float) k, (float) (k / 3.0)));
            acc += (long) s0.invoke(null, (long) k, (short) k, (byte) k, (char) k);
            acc += (int) p0.invoke(t, k);
            if ((k & 63) == 0) acc += ((String) v0.invoke(t, (Object) new String[] {"a" + k, "b"})).length();
            if ((k & 15) == 0) acc += ctor.newInstance((long) k).seed;
            try {
                boom.invoke(t, k);
            } catch (InvocationTargetException e) {
                thrown++;
                Fz.expect(e.getCause() instanceof IllegalStateException && e.getCause().getMessage().equals("boom" + k), "cause");
            }
        }
        ctor.newInstance(9L);
        Target.watch = false;
        Fz.out("invoke.acc", Long.toHexString(acc));
        Fz.out("invoke.thrown", thrown);
        Fz.mix(acc);

        // Argument errors are reported the same way by every backend.
        List<String> errors = new ArrayList<>();
        Object[][] bad = {{t, "x"}, {t}, {null, 1L}, {"notTarget", 1L}, {t, 1.5}, {t, null}};
        for (Object[] b : bad) {
            try {
                Object[] rest = java.util.Arrays.copyOfRange(b, 1, b.length);
                m0.invoke(b[0], rest);
                errors.add("none");
            } catch (Exception e) {
                errors.add(err(e));
            }
        }
        Fz.out("invoke.errors", errors);

        // Fields: widening setters, volatile references, private access, final fields.
        Field fi = Target.class.getField("i"), fl = Target.class.getField("l"), fd = Target.class.getField("d");
        Field fo = Target.class.getField("o"), fs = Target.class.getDeclaredField("s");
        Field ffixed = Target.class.getField("FIXED"), fseed = Target.class.getField("seed");
        fs.setAccessible(true);
        long fh = 0;
        for (int k = 0; k < n; k++) {
            fi.setInt(t, k);
            fl.setInt(t, k * 3);
            fd.setLong(t, k);
            fo.set(t, (k & 1) == 0 ? "s" + (k & 7) : null);
            fs.setShort(t, (short) k);
            fh = fh * 31 + fi.getInt(t) + fl.getLong(t) + (long) fd.getDouble(t) + fs.getInt(t)
                + (fo.get(t) == null ? 0 : fo.get(t).hashCode()) + (int) p0.invoke(t, 1);
        }
        List<String> ferr = new ArrayList<>();
        for (Runnable r : new Runnable[] {
            () -> { try { ffixed.setInt(null, 4); ferr.add("none"); } catch (Exception e) { ferr.add(err(e)); } },
            () -> { try { fseed.setLong(t, 4); ferr.add("none"); } catch (Exception e) { ferr.add(err(e)); } },
            () -> { try { fi.setLong(t, 4); ferr.add("none"); } catch (Exception e) { ferr.add(err(e)); } },
            () -> { try { fi.set(t, "x"); ferr.add("none"); } catch (Exception e) { ferr.add(err(e)); } },
            () -> { try { fi.getInt(null); ferr.add("none"); } catch (Exception e) { ferr.add(err(e)); } }}) r.run();
        fseed.setAccessible(true);
        fseed.setLong(t, 77);
        Fz.out("field.hash", Long.toHexString(fh));
        Fz.out("field.errors", ferr);
        Fz.out("field.finalSetAccessible", fseed.getLong(t));
        Fz.mix(fh);

        // Many distinct members, each past any inflation threshold.
        long mh = 0;
        Method[] many = Many.class.getDeclaredMethods();
        java.util.Arrays.sort(many, java.util.Comparator.comparing(Method::getName));
        Many target = new Many();
        for (int r = 0; r < 40 * Fz.scale; r++)
            for (Method m : many) mh = mh * 31 + (long) m.invoke(java.lang.reflect.Modifier.isStatic(m.getModifiers()) ? null : target, (long) r);
        Fz.out("many.members", many.length);
        Fz.out("many.hash", Long.toHexString(mh));
        Fz.mix(mh);

        // Serialization constructors (generated in the legacy backend).
        int sers = 0;
        long sh = 0;
        for (int k = 0; k < 40; k++) {
            ByteArrayOutputStream bo = new ByteArrayOutputStream();
            try (ObjectOutputStream o = new ObjectOutputStream(bo)) {
                o.writeObject(new Ser(k, "v" + k));
            }
            try (ObjectInputStream in = new ObjectInputStream(new ByteArrayInputStream(bo.toByteArray()))) {
                Ser s = (Ser) in.readObject();
                if (s.a == k && s.b.equals("v" + k)) sers++;
                sh = sh * 31 + s.b.hashCode();
            }
        }
        Fz.out("serialization", sers + " " + Long.toHexString(sh));
        Fz.mix(sh);
        Fz.out("accessors", kinds);
        Fz.out("backend", System.getProperty("jdk.reflect.useDirectMethodHandle", "default") + " "
            + System.getProperty("sun.reflect.inflationThreshold", "-") + " " + System.getProperty("sun.reflect.noInflation", "-")
            + " " + System.getProperty("jdk.reflect.useNativeAccessorOnly", "-"));
        Fz.done();
    }
}
