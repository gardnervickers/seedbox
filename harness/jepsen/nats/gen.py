def scenario(name, comment, version, config, arguments, memory=512):
    lines = [f"# {line}" for line in comment.splitlines()]
    lines += [f"# Generated by gen.py: NATS {version}, nats-{config}.conf.", f"name: {name}", "machines:"]
    for node in ["n1", "n2", "n3", "n4", "n5"]:
        lines += [
            f"  {node}:",
            f"    image: {NATS[version]}",
            "    entrypoint: [/nats-server, -c, /etc/nats/nats.conf]",
            "    environment:",
            f"      SERVER_NAME: {node}",
            f"    memoryMiB: {memory}",
            "    files:",
            f"    - source: nats-{config}.conf",
            "      target: /etc/nats/nats.conf",
            "    # JetStream's store must outlive a crash: keep it on a disk.",
            "    volumes:",
            "      data:",
            "        target: /data",
        ]
    lines += [
        "oracle:",
        f"  image: {PYTHON}",
        "  entrypoint:",
        "  - python3",
        "  - /scenario/nats_jepsen.py",
        *[f"  - \"{argument}\"" for argument in arguments + ["--config", f"{version}/{config}"]],
        "  memoryMiB: 512",
        "  files:",
        "  - source: nats_jepsen.py",
        "    target: /scenario/nats_jepsen.py",
        "  - source: ../../../python/seedbox/__init__.py",
        "    target: /scenario/seedbox/__init__.py",
        "  - source: ../../../python/seedbox/control.py",
        "    target: /scenario/seedbox/control.py",
        "network:",
        "  latency: 1ms",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    for name, spec in SCENARIOS.items():
        (here / f"{name}.yaml").write_text(scenario(name, *spec))
