"""Write the PostgreSQL list-append scenario projects in this directory.

Every scenario runs one postgres machine `pg` (the official image, default
configuration, trust authentication) and the `pg_append.py` oracle, whose
client threads run Jepsen's list-append workload and check the history with
the Elle-style checker in `../elle/list_append.py`. A scenario fails when the
history is not valid for the isolation level's model, so the bug scenarios fail
when they reproduce it. Run `python3 gen.py` after changing this file; the
YAML files are committed.
"""
from pathlib import Path

POSTGRES = {
    "12.3": "docker.io/library/postgres:12.3@sha256:a06e6e6e519b7a329c419f8221edec66cfc45511e8b80e262c12103ba745cf19",
    "12.4": "docker.io/library/postgres:12.4@sha256:a1e04460fdd3c338d6b65a2ab66b5aa2748eb18da3e55bcdc9ef17831ed3ad46",
}
PYTHON = "docker.io/library/python:3.13-alpine@sha256:2d9aefe2fef018a7eb2c13064c89c71929800fd2e5dccdbf52ea5da5bb8d929a"

SCENARIOS = {
    "pg123-serializable": (
        "PostgreSQL 12.3 SERIALIZABLE allows G2-item (Jepsen, 2020-06-12): SSI misses an\n"
        "rw-conflict on a freshly inserted row that a third transaction is updating, so\n"
        "anti-dependency cycles commit. Fixed by 5940ffb in 12.4.",
        "12.3", "serializable", {}),
    "pg124-serializable": (
        "Negative control for pg123-serializable: 12.4 carries 5940ffb, so the same\n"
        "workload must commit no dependency cycle.",
        "12.4", "serializable", {}),
    "pg123-serializable-15s": (
        "pg123-serializable with a 15 s workload, to measure how often one seed reproduces\n"
        "the bug in a short window.",
        "12.3", "serializable", {"duration": 15}),
    "pg124-serializable-15s": (
        "Negative control for pg123-serializable-15s on 12.4.",
        "12.4", "serializable", {"duration": 15}),
    "pg123-repeatable-read": (
        "PostgreSQL REPEATABLE READ is snapshot isolation: G2-item (write skew) is expected\n"
        "by design; the history is checked against snapshot isolation, which allows it.",
        "12.3", "repeatable-read", {}),
}


def scenario(name, comment, version, isolation, options, clients=20):
    duration = options.get("duration", 60)
    lines = [f"# {line}" for line in comment.splitlines()]
    lines += [f"# Generated by gen.py: PostgreSQL {version}, {isolation}.", f"name: {name}", "machines:"]
    lines += [
        "  pg:",
        f"    image: {POSTGRES[version]}",
        "    memoryMiB: 1024",
        "    # pgmon.sh runs the official entrypoint and reports guest memory and OOM kills.",
        "    entrypoint: [bash, /pgmon.sh]",
        "    # Log no ERROR (every serialization failure would be four lines); keep LOG, FATAL, PANIC.",
        "    command: [postgres, -c, log_min_messages=log]",
        "    files:",
        "    - source: pgmon.sh",
        "      target: /pgmon.sh",
        "    environment:",
        "      POSTGRES_HOST_AUTH_METHOD: trust",
    ]
    arguments = ["--isolation", isolation, "--clients", str(clients), "--duration", str(duration),
                 "--label", f"{version}/{isolation}"]
    lines += [
        "oracle:",
        f"  image: {PYTHON}",
        "  entrypoint:",
        "  - python3",
        "  - -u",
        "  - /scenario/pg_append.py",
        *[f"  - \"{argument}\"" for argument in arguments],
        "  memoryMiB: 1024",
        "  files:",
        "  - source: pg_append.py",
        "    target: /scenario/pg_append.py",
        "  - source: ../elle/list_append.py",
        "    target: /scenario/list_append.py",
        "network:",
        "  latency: 1ms",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    for name, spec in SCENARIOS.items():
        (here / f"{name}.yaml").write_text(scenario(name, *spec))
