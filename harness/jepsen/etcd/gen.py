"""Write the etcd 3.4.3 lock scenario projects in this directory.

Every scenario runs five etcd 3.4.3 members n1..n5, five lock-set clients
c1..c5 (`etcd_lock_client.py`, client ci bound to member ni) and the
`etcd_jepsen.py` oracle, which also hosts the protected set. Lease TTL 2 s and
a one-second read-modify-write, as in Jepsen's lock-set test. Run
`python3 gen.py` after changing this file; the YAML files are committed.
"""
from pathlib import Path

# image/Dockerfile copies the pinned gcr.io/etcd-development/etcd:v3.4.3-arm64 binaries into
# an image labelled linux/arm64 (the official tag's config says amd64).
PYTHON = "docker.io/library/python:3.13-alpine@sha256:2d9aefe2fef018a7eb2c13064c89c71929800fd2e5dccdbf52ea5da5bb8d929a"
MEMBERS = ["n1", "n2", "n3", "n4", "n5"]

SCENARIOS = {
    "etcd-healthy": (
        "Baseline: the lock-set workload with no faults.",
        "none", "none"),
    "etcd-lock-pause-holder": (
        "etcd locks do not give mutual exclusion: pause the lock holder's client process\n"
        "(a GC pause) for 3 s, longer than the 2 s lease TTL, after it has read the set.\n"
        "Its lease expires, another client takes the lock, and the paused client resumes\n"
        "and writes its stale set: acknowledged updates are lost.",
        "pause-holder", "none"),
    "etcd-lock-pause-member": (
        "etcd locks do not give mutual exclusion: pause the etcd member the lock holder\n"
        "talks to for 3 s, so the holder's keep-alives stop while it keeps working.",
        "pause-member", "none"),
    "etcd-lock-pause-random-member": (
        "Jepsen's lock-set nemesis: pause a random etcd member for 3 s every 5 s.",
        "pause-random-member", "none"),
    "etcd-11456-partition-waiter": (
        "etcd#11456: while one client holds the lock, isolate the member of a waiting client\n"
        "from the other members for 3 s. The waiter's lease expires; after the heal its\n"
        "Lock RPC still returns success without checking that its key exists.",
        "partition-waiter", "none"),
    "etcd-control-token-pause-holder": (
        "Negative control: the pause-holder schedule, with every read and write fenced by\n"
        "the lock key's create revision. The lock still fails, but no update is lost.",
        "pause-holder", "token"),
    "etcd-control-txn-pause-holder": (
        "Negative control: the pause-holder schedule with the set stored in etcd and every\n"
        "write a transaction that requires the client's lock key to exist.",
        "pause-holder", "txn"),
    "etcd-control-token-partition-waiter": (
        "Negative control for etcd#11456: the partition-waiter schedule with fencing tokens.",
        "partition-waiter", "token"),
}


def scenario(name, comment, mode, guard, duration=120):
    cluster = ",".join(f"{m}=http://{m}:2380" for m in MEMBERS)
    lines = [f"# {line}" for line in comment.splitlines()]
    lines += [f"# Generated by gen.py: mode {mode}, guard {guard}.", f"name: {name}", "machines:"]
    for member in MEMBERS:
        lines += [
            f"  {member}:",
            "    build:",
            "      context: image",
            "    entrypoint: [/usr/local/bin/etcd]",
            "    command:",
            f"    - --name={member}",
            f"    - --data-dir=/var/lib/etcd/{member}",
            "    - --listen-client-urls=http://0.0.0.0:2379",
            f"    - --advertise-client-urls=http://{member}:2379",
            "    - --listen-peer-urls=http://0.0.0.0:2380",
            f"    - --initial-advertise-peer-urls=http://{member}:2380",
            f"    - --initial-cluster={cluster}",
            "    - --initial-cluster-state=new",
            "    - --logger=zap",
            "    - --log-level=info",
            "    environment:",
            "      ETCD_UNSUPPORTED_ARCH: arm64",
            "    memoryMiB: 512",
        ]
    for index, member in enumerate(MEMBERS, 1):
        lines += [
            f"  c{index}:",
            f"    image: {PYTHON}",
            "    entrypoint: [python3, -u, /scenario/etcd_lock_client.py]",
            f"    command: [--name, c{index}, --member, {member}, --guard, {guard}]",
            "    memoryMiB: 384",
            "    files:",
            "    - source: etcd_lock_client.py",
            "      target: /scenario/etcd_lock_client.py",
        ]
    lines += [
        "oracle:",
        f"  image: {PYTHON}",
        "  entrypoint:",
        "  - python3",
        "  - -u",
        "  - /scenario/etcd_jepsen.py",
        *[f"  - \"{argument}\"" for argument in ["--mode", mode, "--guard", guard, "--duration", str(duration)]],
        "  memoryMiB: 512",
        "  files:",
        "  - source: etcd_jepsen.py",
        "    target: /scenario/etcd_jepsen.py",
        "  - source: ../../../python/seedbox/__init__.py",
        "    target: /scenario/seedbox/__init__.py",
        "  - source: ../../../python/seedbox/control.py",
        "    target: /scenario/seedbox/control.py",
        "network:",
        "  latency: 1ms",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    for name, spec in SCENARIOS.items():
        (here / f"{name}.yaml").write_text(scenario(name, *spec))
